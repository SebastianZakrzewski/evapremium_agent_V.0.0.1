import type {
  LeafRetrievalCase,
  LeafRetrievalIntent,
} from './leaf-retrieval-dataset';

function faqGroup(
  idPrefix: string,
  intent: LeafRetrievalIntent,
  slug: string,
  queries: readonly string[],
  opts?: { hardNegatives?: string[] },
): LeafRetrievalCase[] {
  return queries.map((query, index) => ({
    id: `${idPrefix}-${String(index + 1).padStart(2, '0')}`,
    query,
    expectSlugs: [slug],
    intent,
    kind: 'faq',
    hardNegatives: opts?.hardNegatives,
  }));
}

function missGroup(
  idPrefix: string,
  intent: LeafRetrievalIntent,
  queries: readonly string[],
): LeafRetrievalCase[] {
  return queries.map((query, index) => ({
    id: `${idPrefix}-${String(index + 1).padStart(2, '0')}`,
    query,
    expectSlugs: [],
    intent,
    kind: 'faq_miss',
  }));
}

